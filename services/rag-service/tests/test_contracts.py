"""T-C1..T-C4: the Python side of the event contracts in contracts/events/.

The ingest fixtures are generated by a Go test from a real json.Marshal; the status fixtures are
hand-written. The Go tests (internal/events) assert against the same files, so a change to either
side fails both suites.
"""

import json
import re
from datetime import UTC, datetime
from pathlib import Path

import jsonschema
import pytest

from rag.transport.status_event import (
    INGEST_EVENT_TYPE,
    STATUS_EVENT_TYPE,
    IngestEvent,
    InvalidEventError,
    Reason,
    Status,
    StatusEvent,
)

CONTRACTS = Path(__file__).resolve().parents[3] / "contracts" / "events"
FIXTURES = CONTRACTS / "fixtures"

INGEST_SCHEMA = json.loads((CONTRACTS / "ingest_event.schema.json").read_text())
STATUS_SCHEMA = json.loads((CONTRACTS / "status_event.schema.json").read_text())
INGEST_VALIDATOR = jsonschema.Draft202012Validator(INGEST_SCHEMA)
STATUS_VALIDATOR = jsonschema.Draft202012Validator(STATUS_SCHEMA)

INGEST_FIXTURES = sorted(FIXTURES.glob("ingest_event*.json"))
VALID_STATUS_FIXTURES = sorted(FIXTURES.glob("status_*.json"))
INVALID_STATUS_FIXTURES = sorted((FIXTURES / "invalid").glob("*.json"))

HASH = "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"


def accepted(validator: jsonschema.Draft202012Validator, path: Path) -> bool:
    """True when the file is valid JSON that the schema accepts. A file that is not JSON at all
    (status_malformed.json is truncated) counts as rejected."""
    try:
        document = json.loads(path.read_text())
    except json.JSONDecodeError:
        return False
    return not list(validator.iter_errors(document))


def test_fixture_sets_are_not_empty():
    # A glob that matches nothing would make every test below pass for no reason.
    assert len(INGEST_FIXTURES) == 3
    assert len(VALID_STATUS_FIXTURES) == 4
    assert len(INVALID_STATUS_FIXTURES) >= 10


