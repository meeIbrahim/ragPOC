def test_created_at_pattern_is_checked_with_fullmatch_semantics():
    # jsonschema applies "pattern" with re.search, where "$" also matches before a trailing
    # newline; ECMA-262 (and the Go side) do not. Python code must use fullmatch, as below.
    pattern = STATUS_SCHEMA["properties"]["created_at"]["pattern"]
    assert re.fullmatch(pattern, "2026-10-14T10:00:00Z")
    assert re.fullmatch(pattern, "2026-10-14T10:00:00.123456789Z")
    assert not re.fullmatch(pattern, "2026-10-14T10:00:00Z\n")
    assert pattern == INGEST_SCHEMA["properties"]["created_at"]["pattern"]


def test_schema_enums_match_the_python_enums():
    # The reasons and statuses are in three places (PRD, schema, Go). This pins the Python one.
    assert set(STATUS_SCHEMA["properties"]["reason"]["enum"]) == {r.value for r in Reason}
    assert set(STATUS_SCHEMA["properties"]["status"]["enum"]) == {s.value for s in Status}


def test_entry_event_types_match_the_contract():
    assert INGEST_EVENT_TYPE == "IngestionRequest"
    assert STATUS_EVENT_TYPE == "IngestionStatus"


# ---- T-C2: parsing what Go emits

def test_parses_the_go_ingest_fixture_with_nanosecond_created_at():
    event = IngestEvent.parse((FIXTURES / "ingest_event.json").read_bytes())
    assert event.hash == HASH
    assert event.filename == "report.pdf"
    assert event.bucket_path == f"ba/78/{HASH}"
    assert event.size == 1048576
    assert event.attempts == 0
    assert event.schema_version == 1
    # 123456789 ns -> 123456 us: Python datetimes have microsecond precision.
    assert event.created_at == datetime(2026, 10, 14, 10, 0, 0, 123456, tzinfo=UTC)


def test_parses_millisecond_and_whole_second_created_at():
    millis = IngestEvent.parse((FIXTURES / "ingest_event_millis.json").read_text())
    assert (millis.attempts, millis.filename) == (1, "Notes.TXT")
    assert millis.created_at == datetime(2026, 10, 14, 10, 0, 0, 123000, tzinfo=UTC)

