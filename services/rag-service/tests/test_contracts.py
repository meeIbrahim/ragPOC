# ---- T-C3: the serializer reproduces the status fixtures

def fixture_dict(name: str) -> dict:
    return json.loads((FIXTURES / name).read_text())


def rebuild(document: dict) -> StatusEvent:
    created_at = IngestEvent.parse_timestamp(document["created_at"])
    if document["status"] == "INDEXED":
        return StatusEvent.indexed(
            document["hash"], document["attempts"], chunk_count=document.get("chunk_count"),
            id=document["id"], created_at=created_at,
        )
    return StatusEvent.failed(
        document["hash"], document["attempts"], retryable=document["retryable"],
        reason=Reason(document["reason"]), detail=document.get("detail"),
        id=document["id"], created_at=created_at,
    )


@pytest.mark.parametrize("path", VALID_STATUS_FIXTURES, ids=lambda p: p.name)
def test_serializer_output_equals_the_fixture(path):
    expected = json.loads(path.read_text())
    produced = json.loads(rebuild(expected).to_json())
    assert produced == expected


@pytest.mark.parametrize("path", VALID_STATUS_FIXTURES, ids=lambda p: p.name)
def test_serializer_output_matches_the_fixture_after_normalising_id_and_created_at(path):
    expected = json.loads(path.read_text())
    expected_normal = {k: v for k, v in expected.items() if k not in ("id", "created_at")}
    # Built without an explicit id/created_at: the defaults must still produce the same shape.
    if expected["status"] == "INDEXED":
        event = StatusEvent.indexed(expected["hash"], expected["attempts"], chunk_count=expected.get("chunk_count"))
    else:
        event = StatusEvent.failed(
            expected["hash"], expected["attempts"], retryable=expected["retryable"],
            reason=Reason(expected["reason"]), detail=expected.get("detail"),
        )
    produced = json.loads(event.to_json())
    assert {k: v for k, v in produced.items() if k not in ("id", "created_at")} == expected_normal
    assert produced["id"] and produced["id"] != expected["id"]  # a fresh uuid per event
    assert STATUS_VALIDATOR.is_valid(produced)


def test_to_json_is_compact_and_single_line():
    text = StatusEvent.indexed(HASH, 0).to_json()
