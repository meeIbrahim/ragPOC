def test_the_schema_rejects_failed_without_a_reason():
    document = json.loads(StatusEvent.failed(HASH, 0, retryable=True, reason=Reason.INTERNAL).to_json())
    del document["reason"]
    assert not STATUS_VALIDATOR.is_valid(document)


@pytest.mark.parametrize("reason", list(Reason))
@pytest.mark.parametrize("retryable", [True, False])
@pytest.mark.parametrize("attempts", [0, 1, 2, 2147483647])
def test_every_failed_combination_validates_against_the_schema(reason, retryable, attempts):
    document = json.loads(StatusEvent.failed(HASH, attempts, retryable=retryable, reason=reason, detail="short").to_json())
    assert STATUS_VALIDATOR.is_valid(document)
    assert document["retryable"] is retryable and document["reason"] == reason.value


def test_failed_requires_a_reason():
    with pytest.raises(InvalidEventError, match="reason"):
        StatusEvent.failed(HASH, 0, retryable=True, reason=None)


def test_failed_rejects_an_unknown_reason_string():
    with pytest.raises(InvalidEventError, match="reason"):
        StatusEvent.failed(HASH, 0, retryable=True, reason="OUT_OF_COFFEE")


def test_failed_accepts_the_reason_as_a_plain_string():
    assert StatusEvent.failed(HASH, 0, retryable=True, reason="INTERNAL").reason is Reason.INTERNAL


def test_failed_requires_a_boolean_retryable():
    with pytest.raises(InvalidEventError, match="retryable"):
        StatusEvent.failed(HASH, 0, retryable=None, reason=Reason.INTERNAL)
    with pytest.raises(InvalidEventError, match="retryable"):
        StatusEvent.failed(HASH, 0, retryable="yes", reason=Reason.INTERNAL)


